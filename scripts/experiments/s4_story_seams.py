OUT = os.path.join(harness.EXP, 's4_story_seams.json')
DAYS = 7
OUTLETS = 6  # a side must be a story itself: six outlets, as stories are
DEPTH = 3
SHOWN = 6  # each side's most central headlines shown to the judge
MODEL = 'gemma4:26b'
BUCKETS = (0.5, 0.6, 0.7, 0.8, 0.9)
ASK = ["""Two groups of news headlines, from one story on a news site:

Group A:
{a}

Group B:
{b}

Do the two groups report one news event (the same announcement, incident, decision, ruling, report or game, perhaps
with more details or reactions), or two different events (a separate incident, another person's action, a later
development such as a new statement, a response, a vote or an arrest)? Go by what most headlines in each group report.

reason: one sentence
one_event: true or false""", """Group A:
{a}

Group B:
{b}

A news editor has these headlines on one story card. Should they stay on one card, because both groups report one
event, or be two cards, because the groups report different events, even if one led to the other?

reason: one sentence
one_event: true if one card"""]
SCHEMA = {"type": "object", "properties": {"reason": {"type": "string", "maxLength": 400}, "one_event": {"type": "boolean"}},
          "required": ["reason", "one_event"]}


def tfidf(texts: list[str]) -> np.ndarray:
    from sklearn.feature_extraction.text import TfidfVectorizer
    T = TfidfVectorizer().fit_transform(texts)
    return (T @ T.T).toarray()


def best_cut(W: np.ndarray, outlets: list[str]) -> tuple[float, np.ndarray] | None:
    """(normalized cut, the mask of one side) for the cleanest cut whose sides have OUTLETS outlets each, or None"""
    W = W.copy()
    np.fill_diagonal(W, 0)
    d = W.sum(1) + 1e-9
    L = np.eye(len(W)) - W / np.sqrt(np.outer(d, d))
    _, vecs = np.linalg.eigh(L)
    f = vecs[:, 1] / np.sqrt(d)
    best = None
    for cut in np.unique(np.quantile(f, np.linspace(0.05, 0.95, 37))):
        A = f <= cut
        if len({outlets[i] for i in np.flatnonzero(A)}) < OUTLETS or len({outlets[i] for i in np.flatnonzero(~A)}) < OUTLETS:
            continue
        c = W[np.ix_(A, ~A)].sum()
        ncut = c / W[A].sum() + c / W[~A].sum()
        if best is None or ncut < best[0]:
            best = (float(ncut), A)
    return best


def central(idx: list[int], W: np.ndarray, titles: list[str]) -> list[str]:
    s = W[np.ix_(idx, idx)].sum(1)
    out = []
    for k in np.argsort(-s):
        t = ' '.join(titles[idx[k]].split())
        if t not in out:
            out.append(t)
        if len(out) == SHOWN:
            break
    return out


def cuts():
    db = sqlite3.connect(f'file:{os.path.join(Config.data, "data.db")}?mode=ro', uri=True)
    stories = db.execute(f"""select s.id, s.label from story s join story_headline sh on sh.story_id = s.id
                             where s.last_seen > datetime('now', '-{DAYS} days') group by s.id
                             having count(distinct sh.headline_id) >= {2 * OUTLETS}""").fetchall()
    found = []
    for sid, label in stories:
        rows = db.execute('''select h.processed, ag.name, h.title from story_headline sh join headline h on h.id = sh.headline_id
                             join article ar on ar.id = h.article_id join agency ag on ag.id = ar.agency_id
                             where sh.story_id = ? and h.processed is not null''', (sid,)).fetchall()
        texts, outlets, titles = [r[0] for r in rows], [r[1] for r in rows], [r[2] for r in rows]
        if len(set(outlets)) < 2 * OUTLETS:
            continue
        W = tfidf(texts)
        todo = [(list(range(len(rows))), 0)]
        while todo:
            idx, depth = todo.pop()
            b = best_cut(W[np.ix_(idx, idx)], [outlets[i] for i in idx])
            if not b:
                continue
            ncut, A = b
            a_idx, b_idx = [idx[k] for k in np.flatnonzero(A)], [idx[k] for k in np.flatnonzero(~A)]
            found.append({'story': sid, 'label': label, 'depth': depth, 'ncut': round(ncut, 3),
                          'sizes': [len(a_idx), len(b_idx)],
                          'outlets': [len({outlets[i] for i in a_idx}), len({outlets[i] for i in b_idx})],
                          'a': central(a_idx, W, titles), 'b': central(b_idx, W, titles)})
            if depth + 1 < DEPTH:
                todo += [(a_idx, depth + 1), (b_idx, depth + 1)]
    state = json.load(open(OUT)) if os.path.exists(OUT) else {}
    state['cuts'] = found
    state['stories'] = len(stories)
    json.dump(state, open(OUT, 'w'))
    print(f'cuts: {len(found)} in {len(stories)} stories', flush=True)


def key(c: dict) -> str:
    return json.dumps([c['a'], c['b']])


def judge():
    state = json.load(open(OUT))
    got = state.setdefault('judged', {})
    todo = [c for c in state['cuts'] if key(c) not in got]

    def ask(c):
        a, b = '\n'.join(f'- {t}' for t in c['a']), '\n'.join(f'- {t}' for t in c['b'])
        answers = [llm.complete_json(q.format(a=a, b=b), SCHEMA, max_tokens=400, model=MODEL) for q in ASK]
        return None if any(x is None for x in answers) else [bool(x['one_event']) for x in answers] + \
            [answers[0].get('reason', '')]
    for start in range(0, len(todo), 32):
        part = todo[start:start + 32]
        for c, r in zip(part, llm.parallel(ask, part)):
            if r is not None:
                got[key(c)] = r
        json.dump(state, open(OUT, 'w'))
        print(f'judge: {len(got)}/{len(state["cuts"])}', flush=True)


def report():
    state = json.load(open(OUT))
    got = state.get('judged', {})
    rows = []
    for c in state['cuts']:
        v = got.get(key(c))
        if v and v[0] == v[1]:  # both wordings alike
            rows.append((c['ncut'], not v[0], c, v[2]))
    lines = [f"S4 seams in stories: {len(state['cuts'])} cuts in {state['stories']} stories of the last {DAYS} days, "
             f"{len(rows)} judged alike under both wordings; a cut is right when the two sides are two events"]
    lo = 0.0
    for hi in BUCKETS + (9.0,):
        b = [r for r in rows if lo <= r[0] < hi]
        if b:
            lines.append(f'  cut score {lo:.1f}-{hi:.1f}: {sum(r[1] for r in b)} of {len(b)} right ({np.mean([r[1] for r in b]):.0%})')
        lo = hi
    for line in lines:
        print(line, flush=True)
        harness.note(line)
    print('\nthe cuts, cleanest first:')
    for ncut, right, c, reason in sorted(rows, key=lambda r: r[0]):
        print(f"{ncut:.2f} {'✅ two events' if right else '❌ one event'}  story {c['story']} \"{c['label'][:50]}\" "
              f"{c['sizes'][0]}|{c['sizes'][1]}  A: {c['a'][0][:60]}  B: {c['b'][0][:60]}  ({reason[:120]})")


