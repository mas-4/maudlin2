"""S4 seams in stories (Oct 11, the person's idea: "use embeddings, then tfidf, and use tfidf to examine seams in
stories generated by embeddings"). Stories are made by embeddings, which catch paraphrase but blur one event into the
next on the same subject (S3). Inside each saved story, its headlines' TF-IDF likeness (the person's 2024 word
matching) finds where it would cut most cleanly: spectral bisection, the sweep along the Fiedler vector of the
normalized graph Laplacian for the lowest normalized cut (the links cut, against each side's own links). A plain
"where the word links break" (connected components) almost never fired: a few headlines naming both events bridge
them. A first look at 35 stories ranked cuts by that score, the cleanest first: the Musk honors inside Trump's Nobel
snub (0.44), Yemen's offensive inside the Houthi attacks (0.49), the Maine Senate debate inside Michigan's (0.55), the
Chemistry prize inside the Peace prize (0.56), then wording splits of one event from about 0.60.

Here every cut, a few levels deep, in every story of the last DAYS with both sides OUTLETS outlets or more, judged by
Gemma 26B under two wordings (one event or two; agreement only), for the precision at each cut score: where a split
pass in the hourly run could draw its line.

    s4_story_seams.py cuts | judge | report"""
